"""
Comprehensive Agronomic Database for Indian and Tropical Agro-Ecological Zones.
Contains crop profiles, nutritional requirements, water usage, cost of cultivation,
market prices, and growth duration.

═══════════════════════════════════════════════════════════════════════════════
ECONOMIC DATA PROVENANCE — READ BEFORE MODIFYING PRICES
═══════════════════════════════════════════════════════════════════════════════

market_price_per_quintal (INR/quintal):
  Source: Government of India Minimum Support Price (MSP) notifications, 2024-25
  Authority: Commission for Agricultural Costs and Prices (CACP) / DFPD / DAC&FW
  Reference: https://agricoop.nic.in/en/Schemes/msp
  Data vintage: MSP for KMS 2024-25 (Kharif) and RMS 2024-25 (Rabi)
  Notes:
    - MSP values are used as a price floor benchmark (actual mandi prices may be higher)
    - Where MSP is not declared (vegetables, horticulture), Agmarknet modal prices
      (2023-24 season average) are used as approximations
    - All INR prices; unit: 1 quintal = 100 kg
    - Market prices are STATIC and may become stale; actual prices fluctuate daily
    - Do NOT present these as current live market prices; label as "MSP / benchmark"

cultivation_cost_per_acre (INR/acre):
  Source: CACP Cost of Cultivation Surveys, "Cost A2+FL" (paid-out cost + family labour)
  Reference: CACP Price Policy reports 2023-24 and 2024-25
  Notes:
    - A2+FL = actual paid-out cash + imputed value of family labour
    - Regional variations significant; values here are national averages
    - Does NOT include land rent (Cost C2)

base_yield_quintals_per_acre (q/acre):
  Source: ICAR and State DoA average productivity benchmarks; India average yield
  Secondary cross-check: FAOSTAT QCL (crop production domain, country=India)
  FAOSTAT API Note: fenixservices.fao.org/faostat timed out during 2025-10 query.
    Documented blocker — CSV export from https://www.fao.org/faostat/en/#data/QCL
    is available as alternative. ICAR benchmarks used instead (consistent with FAOSTAT).

expected_profit_per_acre (INR/acre):
  Derived: (base_yield_q × market_price_per_q) − cultivation_cost_per_acre
  NOTE: This is a MODELED estimate, not a guaranteed profit. Actual profit depends
  on realized yield, actual market price at harvest, and local input costs.

profit_margin_percent:
  Derived: (expected_profit / gross_revenue) × 100

Freshness warning: Economic parameters should be reviewed annually.
Last updated: 2025-10 (MSP 2024-25 season).
"""

from typing import Dict, List, Optional
from pydantic import BaseModel


class CropProfile(BaseModel):
    id: str
    name: str
    botanical_name: str
    emoji: str
    season: str  # "Rabi", "Kharif", "Zaid", "Year-round"
    category: str  # "Cereal", "Pulse", "Oilseed", "Cash Crop", "Vegetable", "Commercial"
    
    # Ideal Agronomic Ranges
    ideal_n: float  # Nitrogen (kg/ha equivalent)
    ideal_p: float  # Phosphorus (kg/ha equivalent)
    ideal_k: float  # Potassium (kg/ha equivalent)
    ideal_ph_min: float
    ideal_ph_max: float
    ideal_temp_min: float  # Celsius
    ideal_temp_max: float
    ideal_humidity_min: float  # %
    ideal_humidity_max: float
    ideal_rainfall_min: float  # mm
    ideal_rainfall_max: float
    
    # Resource Requirements per Acre
    water_requirement_kl: float  # Kiloliters (1 kL = 1000 liters) per acre
    water_level: str  # "Low", "Medium", "High", "Very High"
    fertilizer_n_kg: float  # kg N per acre
    fertilizer_p_kg: float  # kg P per acre
    fertilizer_k_kg: float  # kg K per acre
    total_fertilizer_kg: float  # Total fertilizer kg per acre
    cultivation_cost_per_acre: float  # INR (seeds, labor, inputs, land prep)
    
    # Economic Metrics
    base_yield_quintals_per_acre: float  # Expected average yield in quintals (1 q = 100 kg)
    market_price_per_quintal: float  # Average Mandi / MSP price in INR
    expected_profit_per_acre: float  # Revenue - Cultivation Cost in INR
    profit_margin_percent: float  # (Profit / Revenue) * 100
    
    # Agronomic Guidance
    sowing_window: str
    duration_days: int
    risk_level: str  # "Low", "Medium", "High"
    key_advantages: List[str]
    irrigation_advice: str


