def get_crop(crop_id: str) -> Optional[CropProfile]:
    return CROPS_DATABASE.get(crop_id.lower().strip())


def list_crops(season: Optional[str] = None) -> List[CropProfile]:
    if not season or season.lower() == "all":
        return list(CROPS_DATABASE.values())
    return [c for c in CROPS_DATABASE.values() if c.season.lower() == season.lower() or c.season == "Year-round"]


